#!/usr/bin/env python3
"""Train a small digit classifier and export an integer-only version for the CPU.

Model: 64 inputs (8x8 image, pixels 0..16) -> 32 ReLU -> 10 logits.
Integer inference (what the CPU runs, bit-exact):
    acc1[j] = b1[j] + sum_i x[i] * W1[i][j]        int8 weights, int32 accumulate
    h[j]    = clamp(acc1[j] >> SHIFT1, 0, 127)       ReLU + requantize to 7 bits
    out[k]  = b2[k] + sum_j h[j] * W2[j][k]
    class   = argmax(out)
Writes sw/ml_model.h (weights, biases, test images, expected outputs) and
ml/model.npz (the same data for the fault-injection analysis).

    ~/.venvs/rv32i-ml/bin/python ml/train.py
"""
import os
import numpy as np
from sklearn.datasets import load_digits
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPClassifier

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
N_TEST_EXPORT = 100      # test images stored in the CPU program
SEED = 0

X, y = load_digits(return_X_y=True)            # pixels are integers 0..16
X = X.astype(np.int32)
Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.3, random_state=SEED, stratify=y)

clf = MLPClassifier(hidden_layer_sizes=(32,), activation="relu", alpha=1e-3,
                    max_iter=2000, random_state=SEED)
clf.fit(Xtr / 16.0, ytr)
float_acc = clf.score(Xte / 16.0, yte)

# ---- quantize ----
W1f, W2f = clf.coefs_          # (64,32), (32,10)
b1f, b2f = clf.intercepts_
s1 = np.abs(W1f).max() / 127.0
W1 = np.round(W1f / s1).astype(np.int32)
# float pre-activation = (x/16) @ W1f + b1f = (x @ W1) * s1/16 + b1f
b1 = np.round(b1f * 16.0 / s1).astype(np.int32)

def layer1(x):
    return x @ W1 + b1

# choose SHIFT1 so training-set activations fit in 0..127
acc_max = layer1(Xtr).max()
SHIFT1 = max(0, int(np.ceil(np.log2((acc_max + 1) / 128.0))))
h_scale = (2 ** SHIFT1) * s1 / 16.0           # float value of one h unit

s2 = np.abs(W2f).max() / 127.0
W2 = np.round(W2f / s2).astype(np.int32)
b2 = np.round(b2f / (s2 * h_scale)).astype(np.int32)

def checksum(out):
    """Per-image checksum of the 10 logits, computed identically in C:
    s = rotl(s, 5) ^ out[k]  (uint32)"""
    sums = []
    for row in out:
        s = 0
        for v in row:
            s = ((s << 5) | (s >> 27)) & 0xFFFFFFFF
            s ^= int(v) & 0xFFFFFFFF
        sums.append(s)
    return np.array(sums, dtype=np.uint64)

def int_infer(x):
    """Bit-exact reference of the C inference. x: (n,64) ints 0..16."""
    acc1 = layer1(x)
    h = np.clip(acc1 >> SHIFT1, 0, 127)        # arithmetic shift, like C on int32
    out = h @ W2 + b2
    return out, out.argmax(axis=1)

_, pred = int_infer(Xte)
int_acc = (pred == yte).mean()
assert np.abs(W1).max() <= 127 and np.abs(W2).max() <= 127

Xe, ye = Xte[:N_TEST_EXPORT], yte[:N_TEST_EXPORT]
oute, prede = int_infer(Xe)
print(f"float accuracy (test, {len(yte)} images): {float_acc:.4f}")
print(f"int8  accuracy (test, {len(yte)} images): {int_acc:.4f}")
print(f"int8  accuracy (exported {N_TEST_EXPORT}):     {(prede == ye).mean():.4f}")
print(f"SHIFT1={SHIFT1}  max acc1={acc_max}  logit range [{oute.min()}, {oute.max()}]")

# ---- export ----
def carr(name, ctype, a, per_line=16, attr=""):
    a = np.asarray(a).ravel()
    lines = [", ".join(str(int(v)) for v in a[i:i + per_line]) for i in range(0, len(a), per_line)]
    return f"static const {ctype} {name}[{len(a)}]{attr} = {{\n    " + ",\n    ".join(lines) + "\n};\n"

def model_sum(bias_dtype):
    """Integrity checksum over the model's memory image (W1, b1, W2, b2 as
    little-endian words), computed identically in sw/digits.c:
    s = rotl(s, 5) ^ word. A single flipped bit anywhere always changes it."""
    s = 0
    for arr, dt in ((W1, "<i1"), (b1, bias_dtype), (W2, "<i1"), (b2, bias_dtype)):
        for w in np.frombuffer(np.asarray(arr).astype(dt).tobytes(), dtype="<u4"):
            s = (((s << 5) | (s >> 27)) & 0xFFFFFFFF) ^ int(w)
    return s

# int16 biases (the hardened build) must hold the same values
assert max(np.abs(b1).max(), np.abs(b2).max()) < 2**15

h = [
    "// Generated by ml/train.py -- do not edit.",
    "// 8x8 digits MLP: 64 -> 32 (ReLU) -> 10, int8 weights, int32 accumulation.",
    f"// float accuracy {float_acc:.4f}, int8 accuracy {int_acc:.4f} ({len(yte)} test images)",
    "#ifndef ML_MODEL_H", "#define ML_MODEL_H", "#include <stdint.h>",
    "#define N_IN 64", "#define N_HID 32", "#define N_OUT 10",
    f"#define SHIFT1 {SHIFT1}", f"#define N_TEST {N_TEST_EXPORT}", "",
    "// Bias storage type: int32_t by default; the hardened build uses int16_t",
    "// (same values; the largest bias needs 11 bits)",
    "#ifndef BIAS_T", "#define BIAS_T int32_t", "#endif",
    "// expected integrity checksum of W1, b1, W2, b2 (see model_sum in ml/train.py)",
    f"#define MODEL_SUM (sizeof(BIAS_T) == 2 ? 0x{model_sum('<i2'):08x}u : 0x{model_sum('<i4'):08x}u)", "",
    "// W1[i][j] stored row-major (input i, hidden j); W2[j][k] likewise",
    carr("W1", "int8_t", W1, attr=" __attribute__((aligned(4)))"),
    carr("b1", "BIAS_T", b1, attr=" __attribute__((aligned(4)))"),
    carr("W2", "int8_t", W2, attr=" __attribute__((aligned(4)))"),
    carr("b2", "BIAS_T", b2, attr=" __attribute__((aligned(4)))"),
    carr("test_x", "uint8_t", Xe), carr("test_y", "uint8_t", ye),
    "// expected results (bit-exact reference): class and checksum of the 10 logits",
    carr("test_pred", "uint8_t", prede), carr("test_sum", "uint32_t", checksum(oute), per_line=8),
    "#endif", "",
]
open(os.path.join(REPO, "sw", "ml_model.h"), "w").write("\n".join(h))
np.savez(os.path.join(HERE, "model.npz"), W1=W1, b1=b1, W2=W2, b2=b2, SHIFT1=SHIFT1,
         Xte=Xte, yte=yte, Xe=Xe, ye=ye, oute=oute, prede=prede, sume=checksum(oute),
         float_acc=float_acc, int_acc=int_acc)
print("wrote sw/ml_model.h and ml/model.npz")
